    private val rangeStarts: LongArray
    private val rangeEnds: LongArray

    init {
        val raw = cnIpv4Cidrs.mapNotNull(::parseCidr).sortedBy { it.first }
        val merged = ArrayList<Pair<Long, Long>>(raw.size)
        for ((s, e) in raw) {
            val prev = merged.lastOrNull()
            if (prev != null && s <= prev.second + 1L) {
                merged[merged.lastIndex] = prev.first to maxOf(prev.second, e)
            } else {
                merged += s to e
            }
        }
        rangeStarts = LongArray(merged.size) { merged[it].first }
        rangeEnds = LongArray(merged.size) { merged[it].second }
    }

    /** 判断主机（域名、IPv4 或 IPv6 字面量）是否属于中国大陆网络或 .cn / 国内常见站点。 */
    fun shouldBypass(host: String?): Boolean {
        val h = host?.trim()?.trim('[', ']')?.trimEnd('.')?.lowercase()?.takeIf { it.isNotEmpty() } ?: return false
        parseIpv4(h)?.let { ip -> return isCnIpv4(ip) }
        if (':' in h) return isCnIpv6(h)
        // 先检查主域名与后缀精确匹配
        var candidate = h
        while (candidate.isNotEmpty()) {
            if (candidate in cnSuffixes) return true
            val dot = candidate.indexOf('.')
            if (dot < 0) break
            candidate = candidate.substring(dot + 1)
        }
        return false
    }

    internal fun isCnIpv4(ip: Long): Boolean {
        var lo = 0
        var hi = rangeStarts.lastIndex
        while (lo <= hi) {
            val mid = (lo + hi) ushr 1
            val s = rangeStarts[mid]
            if (ip < s) {
                hi = mid - 1
            } else if (ip > rangeEnds[mid]) {
                lo = mid + 1
            } else {
                return true
            }
        }
        return false
    }

    internal fun isCnIpv6(host: String): Boolean {
        val norm = expandIpv6PrefixHextets(host) ?: return false
        val h0 = norm.first
        val h1 = norm.second
        return when (h0) {
            0x2408 -> (h1 and 0xF000) == 0x8000 // 中国联通 2408:8000::/20
            0x2409 -> (h1 and 0xF000) == 0x8000 // 中国移动 2409:8000::/20
            0x240e -> (h1 and 0xC000) == 0x0000 // 中国电信 240e::/18
            0x240c -> (h1 and 0xF000) == 0x0000 // 中国广电 240c::/20
            0x2400 -> h1 == 0xdd00 || h1 == 0x3200 || h1 == 0xa480 // CNNIC / 阿里云
            0x2402 -> h1 == 0x4e00 // 腾讯云
            0x2001 -> h1 == 0x0da8 || h1 == 0x0250 // CERNET 教育网
            else -> false
        }
    }

    internal fun parseIpv4(host: String): Long? {
        val parts = host.split('.')
        if (parts.size != 4) return null
        var acc = 0L
        for (p in parts) {
            if (p.isEmpty() || p.length > 3) return null
            val v = p.toIntOrNull() ?: return null
            if (v !in 0..255) return null
            acc = (acc shl 8) or v.toLong()
        }
        return acc
    }

    private fun parseCidr(cidr: String): Pair<Long, Long>? {
        val slash = cidr.indexOf('/')
        if (slash <= 0) return null
        val base = parseIpv4(cidr.substring(0, slash)) ?: return null
        val prefix = cidr.substring(slash + 1).toIntOrNull()?.takeIf { it in 1..32 } ?: return null
        val mask = (0xFFFFFFFFL shl (32 - prefix)) and 0xFFFFFFFFL
        val start = base and mask
        val end = start or (mask.inv() and 0xFFFFFFFFL)
        return start to end
    }

    private fun expandIpv6PrefixHextets(host: String): Pair<Int, Int>? {
        val clean = host.substringBefore('%')
        val dbl = clean.indexOf("::")
        val leftStr = if (dbl >= 0) clean.substring(0, dbl) else clean
        val leftParts = if (leftStr.isEmpty()) emptyList() else leftStr.split(':')
        if (leftParts.isEmpty()) return null
        val h0 = leftParts[0].toIntOrNull(16) ?: return null
        val h1 = leftParts.getOrNull(1)?.toIntOrNull(16) ?: 0
        return h0 to h1
    }
